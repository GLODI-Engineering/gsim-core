    #[test]
    fn emits_subckt_def_x_cards_with_positional_connections() {
        let mut b = ModelBuilder::new("m", "M", 10);
        let def = SubcktDef::new("leaf", "LEAF").unwrap().with_ports([
            SubcktPort::new("a", "physical-electrical").unwrap(),
            SubcktPort::new("b", "physical-electrical").unwrap(),
            SubcktPort::new("ctrl", "signal").unwrap(),
        ]);
        let mut def = def;
        // Body: a boundary pseudo-block, one resistor across a-b.
        {
            let mut body = ModelBuilder::new("__leaf", "leaf", 10);
            add(
                &mut body,
                "leaf",
                "spice-subckt.boundary",
                Paradigm::SpiceSubckt,
                json!({}),
            );
            add(
                &mut body,
                "Rin",
                "passive.resistor",
                Paradigm::PhysicalNetwork,
                json!({"R": 1000.0}),
            );
            elec(&mut body, "leaf", "a", "Rin", "p1");
            elec(&mut body, "Rin", "p2", "leaf", "b");
            let m = body.into_model();
            def.blocks = m.blocks;
            def.wires = m.wires;
        }
        b.add_subckt_def(def).unwrap();
        b.instantiate_subckt(NewSubcktInstanceSpec::new("leaf", (0, 0)).with_id("X1"))
            .unwrap();
        b.instantiate_subckt(NewSubcktInstanceSpec::new("leaf", (0, 0)).with_id("X2"))
            .unwrap();
        add(
            &mut b,
            "C1",
            "source.const",
            Paradigm::SignalFlow,
            json!({"value": 7.0}),
        );
        add(
            &mut b,
            "gnd",
            "routing.ground",
            Paradigm::PhysicalNetwork,
            json!({}),
        );
        elec(&mut b, "X1", "b", "X2", "a");
        elec(&mut b, "X1", "a", "gnd", "p");
        elec(&mut b, "X2", "b", "gnd", "p");
        for x in ["X1", "X2"] {
            b.connect(
                Endpoint::new("C1", "out"),
                Endpoint::new(x, "ctrl"),
                "signal",
                ConnectOptions::default(),
            )
            .unwrap();
        }

        let out = compile(&b.into_model(), "general-simulator").unwrap();
        assert!(
            out.netlist.contains(".subckt LEAF a b ctrl"),
            "{}",
            out.netlist
        );
        assert!(out.netlist.contains(".ends LEAF"), "{}", out.netlist);
        // Inside the def, the boundary ports name the nets -- so the resistor lands on a/b.
        assert!(out.netlist.contains("Rin a b 1000"), "{}", out.netlist);
        // Positional X cards: two electrical nets then the signal *block name*.
        assert!(
            out.netlist.contains("X1 0 n_X1_b C1 LEAF"),
            "{}",
            out.netlist
        );
        assert!(
            out.netlist.contains("X2 n_X1_b 0 C1 LEAF"),
            "{}",
            out.netlist
        );
    }

